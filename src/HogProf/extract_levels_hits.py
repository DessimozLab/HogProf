def compare_all_vs_all(taxa_hsig_dict, outputfile):
    print("Performing all vs all comparison...")
    for level, [level_T, network_id_to_hsig] in taxa_hsig_dict.items():
        out_eps = outputfile.replace(".csv",f"{level}.eps")
        ids = list(network_id_to_hsig.keys())
        sigs = [network_id_to_hsig[i] for i in ids]
        jkern = np.array([
            [sig1.jaccard(sig2) if i != j else 0
            for j, sig2 in enumerate(sigs)]
            for i, sig1 in enumerate(sigs)
        ])
        # convert to distance for clustering
        dist = 1 - jkern
        ### now apply threshold
        jkern_plot = jkern.copy()
        jkern_plot[jkern_plot < level_T] = 0
        print(jkern)
        g = sns.clustermap(
            dist,
            xticklabels=ids,
            yticklabels=ids,
            figsize=(20, 20),
            cmap="viridis_r"  # reversed so small distance = high similarity
        )
        g.savefig(out_eps, format='eps')
        print(f"Created file: {out_eps}")

